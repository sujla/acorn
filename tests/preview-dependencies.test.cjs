const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const http = require('node:http');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { prepareDependencies } = require('../src/main/preview-dependencies.cjs');
const { compilePreview } = require('../src/main/preview-compiler.cjs');
const { yarnPlan } = require('../src/main/preview-yarn.cjs');
const yarnConfig = Buffer.from('nodeLinker: node-modules\n');
const yarnLock = Buffer.from('# This file is generated by running "yarn install" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 10\n  cacheKey: 10c0\n\n"fixture@workspace:.":\n  version: 0.0.0-use.local\n  resolution: "fixture@workspace:."\n  languageName: unknown\n  linkType: soft\n');

async function fixture(t) {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'acorn-install-test-'));
  t.after(() => fs.rm(temporary, { recursive: true, force: true }));
  const root = path.join(temporary, 'snapshot');
  const repositoryPath = path.join(temporary, 'repo');
  const cacheRoot = path.join(temporary, 'cache');
  for (const directory of [root, repositoryPath]) await fs.mkdir(directory);
  const pkg = { name: 'fixture', version: '1.0.0', dependencies: { example: '1.0.0' } };
  const lock = { name: 'fixture', version: '1.0.0', lockfileVersion: 3, packages: { '': pkg } };
  for (const directory of [root, repositoryPath]) {
    await fs.writeFile(path.join(directory, 'package.json'), JSON.stringify(pkg));
    await fs.writeFile(path.join(directory, 'package-lock.json'), JSON.stringify(lock));
  }
  return { temporary, root, repositoryPath, cacheRoot, pkg, lock };
}

test('matching dependencies use live packages without invoking installer', async t => {
  const options = await fixture(t);
  const result = await prepareDependencies({ ...options, install: () => assert.fail('must not install') });
  assert.equal(result.root, options.repositoryPath);
  assert.equal(result.isolated, false);
});

test('Yarn plans reject unsupported managers, configuration, and dependency sources before installation', () => {
  const pkg = { name: 'fixture', packageManager: 'yarn@4.18.0' };
  assert.equal(yarnPlan(pkg, yarnLock, yarnConfig).version, '4.18.0');
  assert.throws(() => yarnPlan({ ...pkg, packageManager: 'yarn@latest' }, yarnLock, yarnConfig), /exact Yarn 4/);
  assert.throws(() => yarnPlan(pkg, null, yarnConfig), /yarn.lock is missing/);
  for (const config of ['nodeLinker: pnp', 'nodeLinker: node-modules\nplugins: []', 'yarnPath: ./evil.cjs', 'packageExtensions: {}']) {
    assert.throws(() => yarnPlan(pkg, yarnLock, Buffer.from(config)), /custom Yarn settings/);
  }
  for (const spec of ['file:../other', 'git+https://example.com/repo.git', 'owner/repo', 'workspace:*']) {
    assert.throws(() => yarnPlan({ ...pkg, dependencies: { example: spec } }, yarnLock, yarnConfig), /local, Git/);
  }
  const badLock = Buffer.concat([yarnLock, Buffer.from('\n"example@*":\n  resolution: "example@git+https://example.com/repo.git"\n')]);
  assert.throws(() => yarnPlan(pkg, badLock, yarnConfig), /local, Git/);
});

async function yarnFixture(t) {
  const options = await fixture(t);
  const pkg = { name: 'fixture', version: '1.0.0', packageManager: 'yarn@4.18.0', scripts: { postinstall: 'node -e "require(\'fs\').writeFileSync(\'SCRIPT_RAN\',\'bad\')"' } };
  await fs.writeFile(path.join(options.root, 'package.json'), JSON.stringify(pkg));
  await fs.writeFile(path.join(options.root, 'yarn.lock'), yarnLock);
  await fs.writeFile(path.join(options.root, '.yarnrc.yml'), yarnConfig);
  return options;
}

test('Yarn selects its declared manager even with a stale npm lock; changes invalidate cache', async t => {
  const options = await yarnFixture(t);
  let calls = 0;
  const install = async ({ directory, manager }) => {
    calls++;
    assert.equal(manager.name, 'yarn');
    assert.equal(manager.version, '4.18.0');
    await assert.rejects(fs.access(path.join(directory, 'package-lock.json')));
    assert.deepEqual(await fs.readFile(path.join(directory, 'yarn.lock')), yarnLock);
  };
  const first = await prepareDependencies({ ...options, install });
  assert.equal((await prepareDependencies({ ...options, install })).key, first.key);
  assert.equal(calls, 1);
  const pkg = JSON.parse(await fs.readFile(path.join(options.root, 'package.json')));
  pkg.packageManager = 'yarn@4.17.0';
  await fs.writeFile(path.join(options.root, 'package.json'), JSON.stringify(pkg));
  assert.notEqual((await prepareDependencies({ ...options, install: async () => {} })).key, first.key);
  await fs.writeFile(path.join(options.root, '.yarnrc.yml'), 'nodeLinker: pnp\n');
  await assert.rejects(prepareDependencies({ ...options, install }), /custom Yarn settings/);
});

test('a modified Yarn lockfile is not cached', async t => {
  const options = await yarnFixture(t);
  await assert.rejects(prepareDependencies({ ...options, install: ({ directory }) => fs.appendFile(path.join(directory, 'yarn.lock'), '# changed') }), /changed the revision/);
  assert.deepEqual(await fs.readdir(path.join(options.cacheRoot, 'installed-dependencies')), []);
});

test('actual Yarn 4 install disables root scripts and reuses its isolated cache', { skip: !process.env.ACORN_TEST_YARN, timeout: 60000 }, async t => {
  const options = await yarnFixture(t);
  const result = await prepareDependencies(options);
  await assert.rejects(fs.access(path.join(result.root, 'SCRIPT_RAN')));
  assert.deepEqual(await fs.readFile(path.join(result.root, 'yarn.lock')), yarnLock);
  assert.equal((await prepareDependencies(options)).key, result.key);
  assert.deepEqual(await fs.readFile(path.join(options.root, 'yarn.lock')), yarnLock);
  await assert.rejects(fs.access(path.join(options.repositoryPath, 'node_modules')));
  // An older lock format would require migration: never silently accept it.
  const outdated = yarnLock.toString().replace('version: 10', 'version: 8');
  await fs.writeFile(path.join(options.root, 'yarn.lock'), outdated);
  await assert.rejects(prepareDependencies(options), /Could not prepare dependencies/);
  assert.equal(await fs.readFile(path.join(options.root, 'yarn.lock'), 'utf8'), outdated);
  assert.equal((await fs.readdir(path.join(options.cacheRoot, 'installed-dependencies'))).length, 1);
});

test('failed installs are removed, retried, and concurrent requests share one install', async t => {
  const options = await fixture(t);
  await fs.writeFile(path.join(options.repositoryPath, 'package-lock.json'), '{}');
  let attempts = 0;
  const install = async ({ directory }) => {
    attempts++;
    await fs.mkdir(path.join(directory, 'node_modules'));
    if (attempts === 1) throw new Error('fixture install failure');
  };
  await assert.rejects(prepareDependencies({ ...options, install }), /fixture install failure/);
  assert.deepEqual(await fs.readdir(path.join(options.cacheRoot, 'installed-dependencies')), []);
  const [a, b] = await Promise.all([prepareDependencies({ ...options, install }), prepareDependencies({ ...options, install })]);
  assert.equal(a.root, b.root);
  assert.equal(attempts, 2);
  await prepareDependencies({ ...options, install });
  assert.equal(attempts, 2);
});

test('actual npm install builds the historical package, reuses it across source changes, and leaves live packages untouched', { timeout: 60000 }, async t => {
  const options = await fixture(t);
  const packageDir = path.join(options.temporary, 'package');
  await fs.mkdir(packageDir);
  await fs.writeFile(path.join(packageDir, 'package.json'), JSON.stringify({ name: 'example', version: '1.0.0', main: 'index.js', scripts: { postinstall: 'node -e "require(\'fs\').writeFileSync(\'SCRIPT_RAN\',\'bad\')"' } }));
  await fs.writeFile(path.join(packageDir, 'index.js'), 'exports.value = "HISTORICAL_PACKAGE";');
  const tarballPath = path.join(options.temporary, 'example.tgz');
  execFileSync('tar', ['-czf', tarballPath, '-C', options.temporary, 'package']);
  const tarball = await fs.readFile(tarballPath);
  let downloads = 0;
  const server = http.createServer((_req, res) => { downloads++; res.writeHead(200, { 'content-type': 'application/octet-stream' }); res.end(tarball); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  options.lock.packages['node_modules/example'] = { version: '1.0.0', resolved: `http://127.0.0.1:${server.address().port}/example.tgz`, integrity: 'sha512-' + crypto.createHash('sha512').update(tarball).digest('base64'), hasInstallScript: true };
  await fs.writeFile(path.join(options.root, 'package-lock.json'), JSON.stringify(options.lock));
  await fs.writeFile(path.join(options.root, 'index.html'), '<script type="module" src="/main.js"></script>');
  await fs.writeFile(path.join(options.root, 'main.js'), 'import {value} from "example"; document.body.textContent=value;');
  const live = path.join(options.repositoryPath, 'node_modules/example');
  await fs.mkdir(live, { recursive: true });
  await fs.writeFile(path.join(live, 'package.json'), '{"name":"example","version":"2.0.0","main":"index.js"}');
  await fs.writeFile(path.join(live, 'index.js'), 'exports.value="LIVE_PACKAGE";');
  // A warm artifact using current packages must switch when the live lock changes.
  await fs.writeFile(path.join(options.repositoryPath, 'package-lock.json'), JSON.stringify(options.lock));
  const liveArtifact = await compilePreview(options);
  assert.equal((await compilePreview(options)).cached, true);
  await fs.writeFile(path.join(options.repositoryPath, 'package-lock.json'), '{}');
  const statuses = [];
  const first = await compilePreview({ ...options, onProgress: status => statuses.push(status) });
  assert.notEqual(first.dependencyRoot, liveArtifact.dependencyRoot);
  assert.ok(downloads > 0);
  assert.ok(statuses.some(status => status.includes('Installing libraries')));
  const dependencyFiles = await fs.readdir(first.dependencyRoot);
  const bundle = await fs.readFile(path.join(first.dependencyRoot, dependencyFiles.find(file => file.endsWith('.js'))), 'utf8');
  assert.match(bundle, /HISTORICAL_PACKAGE/);
  assert.doesNotMatch(bundle, /LIVE_PACKAGE/);
  const installed = await prepareDependencies(options);
  await assert.rejects(fs.access(path.join(installed.root, 'node_modules/example/SCRIPT_RAN')));
  assert.equal(await fs.readFile(path.join(live, 'index.js'), 'utf8'), 'exports.value="LIVE_PACKAGE";');
  const count = downloads;
  const cachedStatuses = [];
  assert.equal((await compilePreview({ ...options, onProgress: status => cachedStatuses.push(status) })).cached, true);
  assert.ok(cachedStatuses.includes('Reusing cached preview…'));
  assert.ok(!cachedStatuses.some(status => status.includes('Installing')));
  await fs.appendFile(path.join(options.root, 'main.js'), '\ndocument.body.id="changed-source";');
  const reusedStatuses = [];
  const changed = await compilePreview({ ...options, onProgress: status => reusedStatuses.push(status) });
  assert.ok(reusedStatuses.includes('Reusing installed libraries for this revision…'));
  assert.ok(reusedStatuses.includes('Reusing cached library bundle…'));
  assert.ok(!reusedStatuses.some(status => status.includes('Installing')));
  assert.equal(changed.dependencyCached, true);
  assert.equal(downloads, count);
  // Dynamic imports use the same isolated tree without falling back to live packages.
  await fs.writeFile(path.join(options.root, 'main.js'), 'import("example").then(x=>document.body.textContent=x.value);');
  const dynamic = await compilePreview(options);
  assert.match(await fs.readFile(path.join(dynamic.root, '_acorn/entry-0.js'), 'utf8'), /HISTORICAL_PACKAGE/);
  assert.equal(downloads, count);
});
